import { readFile, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { expect, test } from '@playwright/test'

test.describe.configure({ mode: 'serial' })

test('reviews and confirms versioned local Spec and Tickets artifacts', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/')
  await expect(page.getByText('Fixture Product / front')).toBeVisible()

  await page.getByLabel('需求标题').fill('优化首页空状态文案')
  await page.getByRole('textbox', { name: '目标页面' }).fill('/competition')
  await page.getByLabel('期望结果').fill('把空状态文案改得更明确，同时保留现有页面结构')
  await page.getByRole('button', { name: '建立产品需求' }).click()
  await expect(page.getByText('成功结果', { exact: true })).toBeVisible()

  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-slow-grilling'), 'slow\n')
  await page.getByLabel('回复 Grilling').fill('用户应看到更明确的空状态文案；范围保持 apps/front；以真实预览和无新增控制台错误验收。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('Agent 正在整理当前 frontier…')).toBeVisible()
  await page.getByRole('button', { name: '停止 Turn' }).click()
  await expect(page.getByRole('button', { name: '重试当前阶段' })).toBeVisible()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('共同理解：', { exact: true })).toBeVisible()
  await expect(page.getByText('共同理解：按已确认结果')).toBeVisible()
  await page.getByRole('button', { name: '确认共同理解' }).click()

  await expect(page.getByText('Spec v1')).toBeVisible()
  await expect(page.getByText('当前空状态没有说明用户下一步可以做什么')).toBeVisible()
  await expect(page.getByText('待确认')).toBeVisible()
  await expect(page.getByLabel('回复 Spec')).toBeVisible()
  await expect(page.getByRole('button', { name: '确认当前 Spec' })).toBeVisible()
  await expect(page.getByLabel('对话工作流').locator('[data-state="current"]')).toContainText('Spec')

  const dataRoot = path.join(os.tmpdir(), 'product-agent-workbench-e2e-data')
  const requirementPath = path.join(dataRoot, 'current-requirement.json')
  const first = JSON.parse(await readFile(requirementPath, 'utf8'))
  expect(first.tickets).toEqual([])
  await expect(readFile(path.join(dataRoot, first.specVersions[0].path), 'utf8')).resolves.toContain('## Problem Statement')

  await page.reload()
  await expect(page.getByText('Spec v1')).toBeVisible()
  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-fail-spec'), 'fail\n')
  await page.getByLabel('回复 Spec').fill('方案里补充明确的下一步引导')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('paragraph').filter({ hasText: 'fixture Spec failure' })).toBeVisible()
  await expect(page.getByText('Spec v1')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '重试当前阶段' })).toBeVisible()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('Spec v2')).toBeVisible()
  await expect(page.getByText('已失效').first()).toBeVisible()
  await expect(page.getByText('使用更具体的空状态文案，并补充下一步引导')).toBeVisible()

  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-slow-spec'), 'slow\n')
  await page.getByLabel('回复 Spec').fill('再明确一点测试决定')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('Agent 正在整理 Spec…')).toBeVisible()
  await page.getByRole('button', { name: '停止 Turn' }).click()
  await page.reload()
  await expect(page.getByText('Spec v2')).toBeVisible()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('Spec v3')).toBeVisible()

  await page.getByRole('button', { name: '确认当前 Spec' }).click()
  await expect(page.getByLabel('对话工作流').locator('[data-state="current"]')).toContainText('Tickets')
  await expect(page.getByText('Spec 已确认')).toBeVisible()
  await expect(page.getByText('Tickets v1')).toBeVisible()
  await expect(page.getByText('TICKET-01 · 交付赛事页空状态引导')).toBeVisible()
  await expect(page.getByLabel('回复 Tickets')).toBeVisible()
  await expect(page.getByRole('button', { name: '确认当前 Tickets' })).toBeVisible()
  await expect(page.getByRole('button', { name: '创建分支并执行' })).toHaveCount(0)

  await page.getByLabel('回复 Tickets').fill('修改 Spec：补充保留现有页面结构的实现决定')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('Spec v4')).toBeVisible()
  await expect(page.getByLabel('对话工作流').locator('[data-state="current"]')).toContainText('Spec')
  await page.getByRole('button', { name: '确认当前 Spec' }).click()
  await expect(page.getByText('Tickets v2')).toBeVisible()

  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-fail-tickets'), 'fail\n')
  await page.getByLabel('回复 Tickets').fill('拆成两票，并明确第二票依赖第一票')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('paragraph').filter({ hasText: 'fixture Tickets failure' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('Tickets v3')).toBeVisible()
  await expect(page.getByText('已失效').first()).toBeVisible()
  await expect(page.getByText('TICKET-02 · 验证保留现有结构')).toBeVisible()

  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-slow-tickets'), 'slow\n')
  await page.getByLabel('回复 Tickets').fill('保留两票，再明确验收条件')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('Agent 正在整理执行票…')).toBeVisible()
  await page.getByRole('button', { name: '停止 Turn' }).click()
  await page.reload()
  await expect(page.getByText('正在重新拆分 Tickets，已保留当前修订上下文。')).toBeVisible()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('Tickets v4')).toBeVisible()
  await page.getByRole('button', { name: '确认当前 Tickets' }).click()
  await expect(page.getByLabel('对话工作流').locator('[data-state="current"]')).toContainText('Implement')
  await expect(page.getByText('Tickets 已确认')).toBeVisible()
  await expect(page.getByRole('button', { name: '创建分支并执行' })).toBeVisible()

  const confirmed = JSON.parse(await readFile(requirementPath, 'utf8'))
  expect(confirmed.conversation.phase).toBe('implement')
  expect(confirmed.specVersions.map((version: { status: string }) => version.status)).toEqual(['superseded', 'superseded', 'superseded', 'confirmed'])
  expect(confirmed.ticketVersions.map((version: { status: string }) => version.status)).toEqual(['superseded', 'superseded', 'superseded', 'confirmed'])
  expect(confirmed.tickets.map((ticket: { id: string; blockedBy: string[] }) => ({ id: ticket.id, blockedBy: ticket.blockedBy }))).toEqual([
    { id: 'TICKET-01', blockedBy: [] },
    { id: 'TICKET-02', blockedBy: ['TICKET-01'] },
  ])
  for (const ticket of confirmed.ticketVersions.at(-1).tickets) {
    await expect(readFile(path.join(dataRoot, ticket.path), 'utf8')).resolves.toContain('**Status:** ready-for-agent')
  }

  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-slow-turn'), 'slow\n')
  await page.getByRole('button', { name: '创建分支并执行' }).click()
  await expect(page.getByText('开始 TICKET-01')).toBeVisible()
  await page.getByRole('button', { name: '停止 Turn' }).click()
  await expect(page.getByRole('button', { name: '重试当前阶段' })).toBeVisible()
  await page.reload()
  await writeFile(path.join(os.tmpdir(), 'product-agent-workbench-fail-turn'), 'fail\n')
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByRole('paragraph').filter({ hasText: 'Codex turn 退出码为 1' })).toBeVisible()
  await page.getByRole('button', { name: '重试当前阶段' }).click()
  await expect(page.getByText('正在实现 TICKET-01')).toBeVisible()
  await expect(page.getByText('执行完成').first()).toBeVisible()
  await expect(page.getByRole('button', { name: '通过产品验收' })).toBeVisible({ timeout: 30_000 })
  const implemented = JSON.parse(await readFile(requirementPath, 'utf8'))
  expect(implemented.conversation.implementationThreadId).toBeTruthy()
  expect(implemented.conversation.implementationThreadId).not.toBe(implemented.conversation.planningThreadId)
  expect(implemented.branch.requirementBranch).toContain('product/')
  expect(implemented.tickets.every((ticket: { status: string }) => ticket.status === 'completed')).toBe(true)

  await page.getByLabel('提出返修意见').fill('请进一步明确空状态引导')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('region', { name: '产品 Agent 对话' }).getByText('请进一步明确空状态引导')).toBeVisible()
  await page.getByRole('button', { name: '继续当前 Session' }).click()
  await expect(page.getByRole('button', { name: '通过产品验收' })).toBeVisible({ timeout: 30_000 })
  const refined = JSON.parse(await readFile(requirementPath, 'utf8'))
  expect(refined.refinements).toHaveLength(1)
  expect(refined.refinements[0].baselineValidation.length).toBeGreaterThan(0)
  expect(refined.conversation.implementationThreadId).toBe(implemented.conversation.implementationThreadId)

  await page.getByRole('button', { name: '通过产品验收' }).click()
  await expect(page.getByTestId('delivery-card')).toBeVisible()
  const delivered = JSON.parse(await readFile(requirementPath, 'utf8'))
  expect(delivered.stage).toBe('accepted')
  expect(delivered.delivery.revision).toMatch(/^[0-9a-f]{40}$/)
  expect(delivered.delivery.artifactPaths).toContain(`apps/front/.product-agent-workbench/${delivered.specId}/tickets/01-ticket.md`)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('region', { name: '产品 Agent 对话' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
